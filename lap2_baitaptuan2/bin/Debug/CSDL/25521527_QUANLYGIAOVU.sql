CREATE DATABASE QUANLYGIAOVU
USE QUANLYGIAOVU

CREATE TABLE KHOA(
MAKHOA VARCHAR(4),
TENKHOA VARCHAR(40),
NGTLAP SMALLDATETIME,
TRGKHOA CHAR(4),
CONSTRAINT PK_MAKHOA PRIMARY KEY (MAKHOA),
)

CREATE TABLE GIAOVIEN(
MAGV CHAR(4) PRIMARY KEY,
HOTEN VARCHAR(40),
HOCVI VARCHAR(10),
HOCHAM VARCHAR(10),
GIOITINH VARCHAR(3),
NGSINH SMALLDATETIME,
NGVL SMALLDATETIME,
HESO NUMERIC(4,2),
MUCLUONG MONEY,
MAKHOA VARCHAR(4) REFERENCES KHOA(MAKHOA),
)

CREATE TABLE LOP(
MALOP CHAR(3) PRIMARY KEY,
TENLOP VARCHAR(40),
TRGLOP CHAR(5),
SISO TINYINT,
MAGVCN CHAR(4) REFERENCES GIAOVIEN(MAGV),
)
ALTER TABLE LOP 
ADD CONSTRAINT FK_MAHOCVIEN FOREIGN KEY (TRGLOP) REFERENCES HOCVIEN(MAHV);


CREATE TABLE HOCVIEN(
MAHV CHAR(5) PRIMARY KEY,
HO VARCHAR(40),
TEN VARCHAR(10),
NGSINH SMALLDATETIME,
GIOITINH VARCHAR(3),
NOISINH VARCHAR(40),
MALOP CHAR(3) REFERENCES LOP(MALOP),
)

CREATE TABLE MONHOC(
MAMH VARCHAR(10) PRIMARY KEY,
TENMH VARCHAR(40),
TCLT TINYINT,
TCTH TINYINT,
MAKHOA VARCHAR(4) REFERENCES KHOA(MAKHOA),
)

CREATE TABLE DIEUKIEN(
MAMH VARCHAR(10) REFERENCES MONHOC(MAMH),
MAMH_TRUOC VARCHAR(10) REFERENCES MONHOC(MAMH),
CONSTRAINT PK_DIEUKIEN PRIMARY KEY (MAMH, MAMH_TRUOC),
)

CREATE TABLE GIANGDAY(
MALOP CHAR(3) REFERENCES LOP(MALOP),
MAMH VARCHAR(10) REFERENCES MONHOC(MAMH),
MAGV CHAR(4) REFERENCES GIAOVIEN(MAGV),
HOCKY TINYINT,
NAM SMALLINT,
TUNGAY SMALLDATETIME,
DENNGAY SMALLDATETIME,
CONSTRAINT PK_GIANGDAY PRIMARY KEY (MALOP, MAMH),
)

CREATE TABLE KETQUATHI(
MAHV CHAR(5) REFERENCES HOCVIEN(MAHV),
MAMH VARCHAR(10) REFERENCES MONHOC(MAMH),
LANTHI TINYINT,
NGTHI SMALLDATETIME,
DIEM NUMERIC(4,2),
KQUA VARCHAR(10),
CONSTRAINT PK_KETQUATHI PRIMARY KEY (MAHV, MAMH, LANTHI),
)

-- CÂU 1: THÊM 2 THUỘC TÍNH GHICHU, DIEMTB, XEPLOAI CHO HOCVIEN
ALTER TABLE HOCVIEN ADD GHICHU VARCHAR(50)
ALTER TABLE HOCVIEN ADD DIEMTB NUMERIC(4,2)
ALTER TABLE HOCVIEN ADD XEPLOAI VARCHAR(10)

--CÂU 2:
ALTER TABLE HOCVIEN 
ADD CONSTRAINT KIEMTRA_MAHV 
CHECK (MAHV LIKE MALOP + '[0-9][0-9]')

--CÂU 3: GIOITINH CÓ NAM HOẶC NỮ
ALTER TABLE HOCVIEN
ADD CONSTRAINT KIEMTRA_GIOITINH_HV
CHECK ( GIOITINH IN('Nam', 'Nu'))

ALTER TABLE GIAOVIEN
ADD CONSTRAINT KIEMTRA_GIOITINH_GV
CHECK ( GIOITINH IN ('Nam' , 'Nu'))

--CÂU 4: ĐIỂM SỐ 1 LẦN THI TỪ 0 -> 10 VÀ LƯU ĐẾN 2 SỐ LẺ
ALTER TABLE KETQUATHI
ADD CONSTRAINT KIEMTRA_DIEM
CHECK (
DIEM BETWEEN 0 AND 10 -- GIỚI HẠN THANG ĐIỂM
AND DIEM = ROUND(DIEM,2) -- LÀM TRÒN
)

--CÂU 5: KẾT QUẢ THI DAT VÀ KHONG DAT
ALTER TABLE KETQUATHI
ADD CONSTRAINT KIEMTRA_KQUA
CHECK((KQUA = 'Dat' AND DIEM BETWEEN 5 AND 10) OR (KQUA = 'Khong dat' AND DIEM < 5))


-- CÂU 6: HOCVIEN THI 1 MÔN TỐI ĐA 3 LẦN
ALTER TABLE KETQUATHI
ADD CONSTRAINT KIEMTRA_LANTHI
CHECK (LANTHI BETWEEN 1 AND 3)

-- CÂU 7: HỌC KỲ CÓ GIÁ TRỊ TỪ 1 ĐẾN 3
ALTER TABLE GIANGDAY
ADD CONSTRAINT KIEMTRA_HOCKY
CHECK (HOCKY BETWEEN 1 AND 3)

-- CÂU 8: HỌC VỊ CỦA GIÁO VIÊN
ALTER TABLE GIAOVIEN
ADD CONSTRAINT KIEMTRA_HOCVI
CHECK ( HOCVI IN ('CN', 'KS', 'Ths', 'TS', 'PTS'))



